'use strict';
// JS twist estimate for case C_notch_1plate vs the 3-D result in twist_3d.json.  Run: node reference/twist_check.js
const fs = require('fs'), path = require('path');
const BF = require('../docs/engine.js');
const c = JSON.parse(fs.readFileSync(path.join(__dirname, 'cases.json'))).cases.find(k => k.name === 'C_notch_1plate');
const P = BF.defaults();
P.beam.b = c.beam.b; P.beam.d = c.beam.d; P.beam.Ltot = c.beam.Ltot; P.beam.bearing = c.beam.bearing;
P.beam.E = c.beam.E; P.beam.shearFree = 1; P.beam.GoverE = c.beam.G_over_E; P.beam.shear = true;
P.notch = Object.assign({}, c.notch);
const p = c.plates[0];
Object.assign(P.plates[0], { on: true, t: p.t, h: p.h, yb: p.yb, len: p.x1 - p.x0, offset: (p.x0 + p.x1) / 2 - c.beam.Ltot / 2 });
P.plates[1].on = false;
Object.assign(P.fast, { type: 'bolt', size: '1/2', rows: 2, pitch: 8, edge: 4 });
P.fast.slipMult = p.K_x / BF.slipModulus(0.5);
const w = c.load.w_lb_per_in;
const res = BF.solve(P, w, { notch: true, plates: [true, false] });
const tw = BF.twistOf(P, res, w);
const interp = (X, Y, x) => { let k = 0; while (k < X.length - 2 && X[k + 1] < x) k++; const t = (x - X[k]) / (X[k + 1] - X[k]); return Y[k] * (1 - t) + Y[k + 1] * t; };
const d3 = fs.existsSync(path.join(__dirname, 'twist_3d.json')) ? JSON.parse(fs.readFileSync(path.join(__dirname, 'twist_3d.json'))) : null;
const xs = [30, 60, 90, 106.5, 117.5, 150, 180];
const rows = xs.map(x => ({ x, js_deg: interp(tw.X, tw.theta, x) * 180 / Math.PI, d3_deg: d3 ? interp(d3.x, d3.theta_rad, x) * 180 / Math.PI : null }));
console.log('x      3D theta(deg)  JS theta(deg)  JS/3D');
rows.forEach(r => console.log(String(r.x).padEnd(7) + (r.d3_deg === null ? 'n/a' : r.d3_deg.toFixed(4)).padEnd(15) + r.js_deg.toFixed(4).padEnd(15) + (r.d3_deg ? (r.js_deg / r.d3_deg).toFixed(2) : '')));
const maxJS = tw.max * 180 / Math.PI;
let max3 = null, x3 = null;
if (d3) d3.theta_rad.forEach((t, i) => { if (max3 === null || Math.abs(t) > Math.abs(max3)) { max3 = t; x3 = d3.x[i]; } });
console.log('JS peak', maxJS.toFixed(4), 'deg at x =', tw.xMax, '| 3D peak', max3 === null ? 'n/a' : (max3 * 180 / Math.PI).toFixed(4) + ' deg at x = ' + x3, '| ratio', max3 ? (maxJS / (max3 * 180 / Math.PI)).toFixed(2) : '');
console.log('JS zsc (peak shear-centre offset) =', tw.zsc.toFixed(3), 'in');
fs.writeFileSync(path.join(__dirname, 'twist_results.json'), JSON.stringify({ rows, js_peak_deg: maxJS, js_peak_x: tw.xMax, d3_peak_deg: max3 === null ? null : max3 * 180 / Math.PI, d3_peak_x: x3, zsc: tw.zsc }, null, 1));
